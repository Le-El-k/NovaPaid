const LANG_KEY = "novapaid_lang";

let currentLanguage: Language = "fr";
const listeners = new Set<() => void>();

function detectBrowserLanguage(): Language {
  if (typeof navigator === "undefined") return "fr";
  const langs = navigator.languages || [navigator.language];
  for (const lang of langs) {
    const code = lang.toLowerCase().split("-")[0];
    if (code === "fr") return "fr";
    if (code === "en") return "en";
  }
  return "en";
}

function getInitialLanguage(): Language {
  if (typeof window === "undefined") return "fr";
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "fr") return saved;
  } catch {}
  return detectBrowserLanguage();
}

export function setLanguage(lang: Language) {
  currentLanguage = lang;
  try {
    if (typeof window !== "undefined") {
      localStorage.setItem(LANG_KEY, lang);
      document.documentElement.lang = lang;
    }
  } catch {}
  listeners.forEach(fn => fn());
}

export function useLanguage() {
  const [lang, setLang] = useState<Language>(getInitialLanguage);

  useEffect(() => {
    const initial = getInitialLanguage();
    currentLanguage = initial;
    setLang(initial);
    if (typeof document !== "undefined") document.documentElement.lang = initial;
    const handleUpdate = () => setLang(currentLanguage);
    listeners.add(handleUpdate);
    return () => { listeners.delete(handleUpdate); };
  }, []);

  const t = useCallback((key: string, fallback?: string): string => {
    const dict = DICTIONARY[lang] || DICTIONARY.fr;
    return (dict as any)[key] || fallback || (DICTIONARY.fr as any)[key] || String(key);
  }, [lang]);

  return { language: lang, setLanguage, t };
}

export function LanguageSelector({ className = "" }: { className?: string }) {
  const { language, setLanguage: setLang } = useLanguage();

  return (
    <div className={`np-lang-selector ${className}`} role="group" aria-label="Language">
      <button
        type="button"
        className={`np-lang-btn ${language === "fr" ? "is-active" : ""}`}
        onClick={() => setLang("fr")}
        title="Français"
        aria-pressed={language === "fr"}
      >
        🇫🇷 FR
      </button>
      <button
        type="button"
        className={`np-lang-btn ${language === "en" ? "is-active" : ""}`}
        onClick={() => setLang("en")}
        title="English"
        aria-pressed={language === "en"}
      >
        🇬🇧 EN
      </button>
    </div>
  );
}
